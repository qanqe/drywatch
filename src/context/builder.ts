import {formatDuration, type VideoMeta} from '../native/drywatch';

export interface ContextSource {
  key: 'caption' | 'subtitles' | 'transcript' | 'onscreen';
  label: string;
  status: 'extracted' | 'unavailable' | 'not extracted';
  content: string | null;
}

export interface ContextInput {
  title: string;
  sourceUrl: string | null;
  videoName: string;
  meta: VideoMeta | null;
  sources: ContextSource[];
}

const sourceOrder: ContextSource['key'][] = [
  'caption',
  'subtitles',
  'transcript',
  'onscreen',
];

export function buildContextDocument(input: ContextInput): string {
  const lines: string[] = [];

  lines.push(`# ${input.title}`);
  lines.push('');

  lines.push('## Processing');
  lines.push('');
  lines.push(`- Whisper model: small`);
  lines.push(`- App version: v0.0.5`);
  lines.push('');

  lines.push('## Video');
  lines.push('');
  lines.push(`- File: ${input.videoName}`);
  if (input.sourceUrl) {
    lines.push(`- Link: ${input.sourceUrl}`);
  }
  if (input.meta) {
    lines.push(`- Duration: ${formatDuration(input.meta.durationMs)}`);
    if (input.meta.width !== null && input.meta.height !== null) {
      // MediaMetadataRetriever reports dimensions in the video's *encoded*
      // orientation; rotation describes how playback displays them. A 90/270
      // rotation therefore means the stored frame is already the rotated one
      // for modern recordings, so we report the stored values as-is and note
      // the rotation instead of second-guessing orientation.
      lines.push(`- Resolution: ${input.meta.width}x${input.meta.height}`);
      if ((input.meta.rotation ?? 0) !== 0) {
        lines.push(`- Rotation metadata: ${input.meta.rotation}°`);
      }
    }
    lines.push(`- Audio track: ${input.meta.hasAudio ? 'present' : 'none detected'}`);
  }
  lines.push('');

  lines.push('## Sources');
  lines.push('');

  const ordered = sourceOrder
    .map(key => input.sources.find(s => s.key === key))
    .filter((s): s is ContextSource => s !== undefined);

  for (const source of ordered) {
    lines.push(`### ${source.label}`);
    lines.push('');
    if (source.status === 'extracted' && source.content) {
      lines.push(source.content.trim());
    } else if (source.status === 'unavailable') {
      lines.push(`_Not available for this video._`);
    } else {
      lines.push(`_Not extracted yet._`);
    }
    lines.push('');
  }

  lines.push('---');
  lines.push('');
  lines.push(
    'Generated by DryWatch v0.0.5. Source sections are kept separate so the ' +
      'origin of every statement stays clear. Unavailable means the source does ' +
      'not exist for this video; not extracted means the engine has not run.',
  );

  return lines.join('\n');
}

export function defaultTitle(videoName: string): string {
  return videoName.replace(/\.[^.]+$/, '');
}
