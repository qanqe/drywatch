test('shows the two ways to start building video context', async () => {
  let renderer: ReactTestRenderer.ReactTestRenderer | undefined;

  await ReactTestRenderer.act(async () => {
    renderer = ReactTestRenderer.create(<App />);
  });

  const text = renderer!.root
    .findAllByType(Text)
    .map(node => node.props.children);
  expect(text).toContain('A TikTok link');
  expect(text).toContain('A saved video');
  expect(text).toContain('Whisper small · on-device goal');
});

test('builds a context document with labeled source sections', async () => {
  const {buildContextDocument} = require('../src/context/builder');

  const doc = buildContextDocument({
    title: 'Test video',
    sourceUrl: null,
    videoName: 'test.mp4',
    meta: {
      durationMs: 15234,
      width: 1080,
      height: 1920,
      rotation: 90,
      hasAudio: true,
    },
    sources: [
      {key: 'caption', label: 'Caption', status: 'not extracted', content: null},
      {key: 'subtitles', label: 'TikTok subtitles', status: 'unavailable', content: null},
      {key: 'transcript', label: 'Audio transcript', status: 'not extracted', content: null},
      {key: 'onscreen', label: 'On-screen text (OCR)', status: 'not extracted', content: null},
    ],
  });

  expect(doc).toContain('# Test video');
  expect(doc).toContain('0:15');
  expect(doc).toContain('1080x1920');
  expect(doc).toContain('Rotation metadata: 90°');
  expect(doc).toContain('### Caption');
  expect(doc).toContain('_Not extracted yet._');
  expect(doc).toContain('_Not available for this video._');
  expect(doc).toContain('Generated by DryWatch v0.0.4');
  expect(doc).toContain('Whisper model: tiny');
});
